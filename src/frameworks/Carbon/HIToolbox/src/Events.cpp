// Keys that start an accent (dead key) in the Option layer; they match a test character of 0
// as well, but only for key codes without bit 7, and not with Caps Lock.
static const UInt8 g_isCmdCharDeadKeys[] = { 0x0e, 0x20, 0x22, 0x2d, 0x32 };

// With Shift or Command held in the Option layer, the dead keys on I and N also match the
// accent characters '^' and '~'.
static const IsCmdCharKey g_isCmdCharDeadAccents[] = {
	{ 0x22, { 0, 0 }, { '^', 0 }, 0, 0 },
	{ 0x2d, { 0, 0 }, { '~', 0 }, 0, 0 },
};

static bool isCmdCharContains(const UInt8* list, size_t count, UInt8 value)
{
	for (size_t i = 0; i < count; i++) {
		if (list[i] == value)
			return true;
	}
	return false;
}

Boolean IsCmdChar(const EventRecord* event, short test)
{
	// QUIRK: IsCmdChar is deprecated and its contract is not documented. Black-box observation of
	// macOS 27.0.1 (arm64 and x86_64, US layout; tier 2): the result depends only on the key code
	// (message bits 8-15, bit 7 ignored) and on the low byte of `test`. It is true when the key
	// produces that character in the layer chosen by the modifiers: Control selects the control
	// layer, otherwise Option the option layer, otherwise the plain layer (unshifted or shifted
	// character, case-insensitive). The event kind, Command, Shift, Caps Lock (except in the option
	// layer), the message's character byte and the high byte of `test` have no influence, so
	// IsCmdChar(&e, '.') is true for the period key and the keypad decimal key. A NULL event
	// crashes on macOS; here it returns false.
	// Test: tests/src/hitoolbox_iscmdchar.c (probes: vd-upstream mac-probes v375-iscmdchar-*.c)
	if (!event)
		return false;

	const UInt8 keyCode = (event->message >> 8) & 0xFF;
	const UInt8 key = keyCode & 0x7F;
	const UInt8 ch = (UInt8) (test & 0xFF);
	const EventModifiers mods = event->modifiers;
	const size_t keyCount = sizeof(g_isCmdCharKeys) / sizeof(g_isCmdCharKeys[0]);
	const IsCmdCharKey* row = nullptr;

	for (size_t i = 0; i < keyCount; i++) {
		if (g_isCmdCharKeys[i].key == key) {
			row = &g_isCmdCharKeys[i];
			break;
		}
	}

	const bool control = mods & controlKey;
	const bool option = !control && (mods & optionKey);
	const bool caps = mods & alphaLock;

	if (ch == 0) {
		if (isCmdCharContains(g_isCmdCharNoCharKeys, sizeof(g_isCmdCharNoCharKeys), key))
			return true;
		return option && !caps && keyCode == key
			&& isCmdCharContains(g_isCmdCharDeadKeys, sizeof(g_isCmdCharDeadKeys), key);
	}

	if (control)
		return row && row->control == ch;

	if (option) {
		if (row) {
			if (caps && row->capsOption)
				return row->capsOption == ch;
			if (row->option[0] == ch || row->option[1] == ch)
				return true;
		}
		if (mods & (shiftKey | cmdKey)) {
			for (const IsCmdCharKey& accent : g_isCmdCharDeadAccents) {
				if (accent.key == key && accent.option[0] == ch)
					return true;
			}
		}
		return false;
	}

	UInt8 folded = (ch >= 'A' && ch <= 'Z') ? (UInt8) (ch + ('a' - 'A')) : ch;
	return row && (row->plain[0] == folded || row->plain[1] == folded);
}

