// Control character and `capsOption` the only Option-layer character left when Caps Lock is on
// (0 when Caps Lock changes nothing for the key). A 0 entry means no character.
struct IsCmdCharKey
{
	UInt8 key;
	UInt8 plain[2];
	UInt8 option[2];
	UInt8 control;
	UInt8 capsOption;
};

