// Geometry of one button kind. Each rectangle is described per axis; "e" is the
// extent of the passed rectangle on that axis (width for x, height for y).
enum { AX_FIXED, AX_CENTER, AX_INSET, AX_EMPTY, AX_END };  // AX_END: offset from the start is extent + a, size s
typedef struct {
	int8_t mode;
	int8_t a;       // offset (INSET, FIXED), centre correction (CENTER)
	int16_t s;      // size (FIXED, CENTER) or size delta (INSET)
	int16_t t;      // INSET: below this extent the small-extent rule applies, 0: never
	int16_t sc;     // INSET small-extent size
	int16_t n;      // INSET small-extent nominal extent
	int16_t r;      // rounding bias
} AxisSpec;
#define EMPTY_AX AX_EMPTY, 0, 0, 0, 0, 0, 0

typedef struct { AxisSpec x, y; } RectSpec;
typedef struct {
	int16_t w, h;   // natural size of the artwork, 0: follows the rectangle
	uint8_t xCenter; // 1: horizontally centred, 0: left
	uint8_t yCenter; // 1: vertically centred, 0: at the top
	int16_t dx;      // left margin when not centred and not following the rectangle
} DrawSpec;
typedef struct {
	RectSpec content;
	RectSpec background;
	RectSpec label;
	DrawSpec draw;
} ButtonKindSpec;

