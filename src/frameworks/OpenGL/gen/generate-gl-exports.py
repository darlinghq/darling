# Generates gl_exports.c: one exported function per gl* prototype declared in
# the framework's gl.h and glext.h. Each calls the host function after making
# sure the calling thread holds the host binding of its current context (see
# gl_acquire_binding in OpenGL.c). The names, parameter lists and result types
# come from the headers themselves.
#
# The host library this framework re-exports has more gl* names than the
# macOS headers declare: the same functions under the names of the extensions
# that introduced them (glGenQueriesEXT, glGetGraphicsResetStatusKHR,
# glBindVertexArrayOES, ...). An application looks them up by name, so they
# need the binding check as well. gen/extension-names.txt lists those host
# names (the names the host library exports that no macOS header declares and
# whose name is a declared function plus a vendor suffix); each is exported
# with the signature of the function it is a suffixed name of, which the
# extension specifications give it. Entry points that exist only in OpenGL ES,
# in fixed-point or vendor-only form have no such function and stay unwrapped.
# Usage: generate-gl-exports.py <OpenGL framework source dir>
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
root = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(here)
CKW = {'int', 'char', 'short', 'long', 'float', 'double', 'unsigned', 'signed', 'void'}

def split_param(text):
    text = ' '.join(text.split())
    if text == 'void' or text == '':
        return None
    m = re.fullmatch(r'(.*?[\s\*])(\w+)((?:\[[^\]]*\])*)', text)
    if m and m.group(2) not in CKW:
        ty = m.group(1).rstrip()
        if m.group(3):
            ty += ' *'
        return ty
    return text

funcs = {}
order = []
# gl* functions OpenGL.c defines itself (it wraps the host's)
oc = open(os.path.join(root, 'OpenGL.c')).read()
# gl* functions OpenGL.c wraps (it defines override_<name>): exported with the
# same binding check, calling the override instead of the host function
wrapped = set(re.findall(r'^[^\n(;]*?\boverride_(gl[A-Z]\w*)\(', oc, re.M))
own = set(re.findall(r'^(?:CGL_EXPORT )?(?!static)[A-Za-z_][\w \*]*?\b(gl[A-Z]\w*)\(', oc, re.M)) - wrapped
for hdr in ('gl.h', 'glext.h'):
    t = open(os.path.join(root, 'include/OpenGL', hdr)).read()
    t = re.sub(r'/\*.*?\*/', ' ', t, flags=re.S)
    t = re.sub(r'//[^\n]*', ' ', t)
    # one logical line per statement
    t = re.sub(r'^#.*$', ';', t, flags=re.M)
    for m in re.finditer(r'GLAPI\s+([^;()]*?)\s*(?:GLAPIENTRY|APIENTRY)\s*(gl\w+)\s*\(([^;]*?)\)\s*;', t, re.S):
        ret, name, params = m.groups()
        ret = ' '.join(ret.split())
        if name in funcs or name in own:
            continue
        plist = [split_param(p) for p in params.split(',')]
        plist = [p for p in plist if p is not None]
        funcs[name] = (ret, plist)
        order.append(name)

SUFFIXES = ('NVX', 'EXT', 'KHR', 'OES', 'NV', 'ANGLE', 'APPLE', 'IMG', 'QCOM', 'OVR', 'AMD', 'INTEL')
with open(os.path.join(here, 'extension-names.txt')) as f:
    for name in (line.strip() for line in f):
        if not name or name in funcs or name in own:
            continue
        for suffix in SUFFIXES:
            if name.endswith(suffix) and name[:-len(suffix)] in funcs:
                funcs[name] = funcs[name[:-len(suffix)]]
                order.append(name)
                break
        else:
            sys.exit('no function for the extension name ' + name)

out = ['/* Generated by src/frameworks/OpenGL/gen/generate-gl-exports.py from include/OpenGL/gl.h\n'
       '   and glext.h. Do not edit. */\n',
       '#define GL_GLEXT_PROTOTYPES 1\n#include <OpenGL/gl.h>\n#include <OpenGL/glext.h>\n'
       '#include "gl_exports.h"\n\n',
       '#define GL_EXPORT_COUNT %d\n\n' % len(order),
       '/* The host function behind each export (filled in on first use). */\n'
       'void *gl_real_functions[GL_EXPORT_COUNT];\n\n',
       'const char *const gl_export_names[GL_EXPORT_COUNT] = {\n']
out += ['    "%s",\n' % n for n in order]
out.append('};\n\n')
for i, n in enumerate(order):
    ret, plist = funcs[n]
    pdecl = ', '.join('%s%sa%d' % (t, '' if t.endswith('*') else ' ', k) for k, t in enumerate(plist)) or 'void'
    ptypes = ', '.join(plist) or 'void'
    pnames = ', '.join('a%d' % k for k in range(len(plist)))
    void = ret.strip() == 'void'
    if n in wrapped:
        out.append('extern %s override_%s(%s);\n' % (ret, n, pdecl))
        call = 'override_%s(%s)' % (n, pnames)
    else:
        call = '((%s (*)(%s)) GL_REAL(%d))(%s)' % (ret, ptypes, i, pnames)
    out.append('%s %s(%s) {\n' % (ret, n, pdecl))
    out.append('    int acquired = 1;\n')
    out.append('    if (__builtin_expect(!GL_BOUND_HERE(), 0) && !(acquired = gl_acquire_binding()))\n')
    out.append('        return%s;\n' % ('' if void else ' (%s) 0' % ret))
    out.append('    %s%s;\n' % ('' if void else '%s result = ' % ret, call))
    out.append('    if (__builtin_expect(acquired == 2, 0))\n        gl_release_transient();\n')
    out.append('%s}\n' % ('' if void else '    return result;\n'))
open(os.path.join(root, 'gl_exports.c'), 'w').write(''.join(out))
print('generated', len(order), 'exports')
