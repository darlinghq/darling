# Generates gl_trampolines.c: for each host gl* name in gen/trampoline-names.txt
# (names the host library exports that no macOS header declares and that have
# no function to take a signature from, see generate-gl-exports.py) one
# exported assembly entry point. Without a signature it cannot call the host
# function and give a transient binding up afterwards, so it makes the calling
# thread hold the host binding of its current context (gl_trampoline_target in
# OpenGL.c; the thread keeps it until it gives it up the way any other binding
# is given up) and jumps to the host function with the arguments untouched.
# The names in the file come from the symbol table of the host library.
# Usage: generate-gl-trampolines.py <OpenGL framework source dir>
import os, sys
here = os.path.dirname(os.path.abspath(__file__))
root = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(here)
names = [l.strip() for l in open(os.path.join(here, "trampoline-names.txt")) if l.strip()]
out = ["/* Generated by src/frameworks/OpenGL/gen/generate-gl-trampolines.py. Do not edit. */\n",
       "#include \"gl_exports.h\"\n\n",
       "#define GL_TRAMPOLINE_COUNT %d\n" % len(names),
       "const char *const gl_trampoline_names[GL_TRAMPOLINE_COUNT] = {\n"]
out += ["    \"%s\",\n" % n for n in names]
out.append("};\n\n")
out.append("/* The host function behind each entry point (filled in on first use). */\n"
           "void *gl_trampoline_functions[GL_TRAMPOLINE_COUNT];\n\n")

def x64(n, i):
    # the argument registers (rdi rsi rdx rcx r8 r9, rax, xmm0-7) are saved around the call
    l = [".text", ".globl _%s" % n, ".p2align 4", "_%s:" % n]
    l += ["pushq %" + r for r in ("rdi", "rsi", "rdx", "rcx", "r8", "r9", "rax")]
    l += ["subq $128, %rsp"]
    l += ["movdqu %%xmm%d, %d(%%rsp)" % (k, k * 16) for k in range(8)]
    l += ["movl $%d, %%edi" % i, "call _gl_trampoline_target", "movq %rax, %r11"]
    l += ["movdqu %d(%%rsp), %%xmm%d" % (k * 16, k) for k in range(8)]
    l += ["addq $128, %rsp"]
    l += ["popq %" + r for r in ("rax", "r9", "r8", "rcx", "rdx", "rsi", "rdi")]
    l += ["jmp *%r11"]
    return l

def x86(n, i):
    # all arguments are on the stack and stay where they are
    return [".text", ".globl _%s" % n, ".p2align 4", "_%s:" % n,
            "subl $8, %esp", "pushl $%d" % i, "call _gl_trampoline_target", "addl $12, %esp", "jmp *%eax"]

for cond, gen in (("defined(__x86_64__)", x64), ("defined(__i386__)", x86)):
    out.append("#if %s\n" % cond if cond.startswith("defined(__x86_64") else "#elif %s\n" % cond)
    for i, n in enumerate(names):
        out.append("__asm__(\n" + "".join('    "%s\\n"\n' % s for s in gen(n, i)) + ");\n")
out.append("#endif\n")
open(os.path.join(root, "gl_trampolines.c"), "w").write("".join(out))
print("generated", len(names), "trampolines")
