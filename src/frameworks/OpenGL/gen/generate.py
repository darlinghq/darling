# Generates, from gli-dispatch.tsv and gl-macros.tsv (see extract-gli-dispatch.py):
#   include/OpenGL/gliDispatch.h   the dispatch table struct (slot order is the ABI)
#   include/OpenGL/CGLMacro.h      the gl* macros that call through a context's table
#   gli_thunks.inc                 the framework's table entries (one C function per slot)
# Usage: generate.py <OpenGL framework source dir>      (run from anywhere)
import os, re, sys

here = os.path.dirname(os.path.abspath(__file__))
root = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(here)

CKW = {'int', 'char', 'short', 'long', 'float', 'double', 'unsigned', 'signed', 'void'}

def split_param(text):
    """-> (type, name or None) for one parameter declaration."""
    text = ' '.join(text.split())
    if text == 'void':
        return None
    m = re.fullmatch(r'(.*?[\s\*])(\w+)((?:\[[^\]]*\])*)', text)
    if m and m.group(2) not in CKW:
        ty = m.group(1).rstrip()
        if m.group(3):
            ty += ' *'
        return (ty, m.group(2))
    return (text, None)

slots = []
for line in open(os.path.join(here, 'gli-dispatch.tsv')):
    name, ret, params = line.rstrip('\n').split('\t')
    plist = [split_param(p) for p in params.split(' | ')] if params else []
    plist = [p for p in plist if p is not None]
    slots.append((name, ret, plist))

macros = [l.rstrip('\n').split('\t') for l in open(os.path.join(here, 'gl-macros.tsv'))]
macros = [(m + [''] * 5)[:5] for m in macros]

NOTE = ('/* Generated by src/frameworks/OpenGL/gen/generate.py from gen/gli-dispatch.tsv and\n'
        '   gen/gl-macros.tsv. Do not edit. */\n')

def decl_params(plist, named):
    out = []
    for i, (ty, nm) in enumerate(plist):
        out.append('%s %s' % (ty, nm if (named and nm) else 'a%d' % i) if ty[-1] not in '*' else '%s%s' % (ty, (nm if (named and nm) else 'a%d' % i)))
    return out

# ---- gliDispatch.h
with open(os.path.join(root, 'include/OpenGL/gliDispatch.h'), 'w') as f:
    f.write(NOTE)
    f.write('''
#ifndef _GLIDISPATCH_H
#define _GLIDISPATCH_H

#include <OpenGL/gl.h>
#include <OpenGL/glext.h>
#include <OpenGL/gliContext.h>

#ifdef __cplusplus
extern "C" {
#endif

/* The functions of one context's dispatch table. The first argument of every
   entry is the context's renderer (the "rend" member of its CGLContextObj). The
   order of the members is part of the binary interface. */
typedef struct __GLIFunctionDispatchRec {
''')
    for name, ret, plist in slots:
        args = ['GLIContext ctx'] + decl_params(plist, True)
        f.write('    %s (*%s)(%s);\n' % (ret, name, ', '.join(args)))
    f.write('''} GLIFunctionDispatch;

#ifdef __cplusplus
}
#endif

#endif /* _GLIDISPATCH_H */
''')

# ---- CGLMacro.h
with open(os.path.join(root, 'include/OpenGL/CGLMacro.h'), 'w') as f:
    f.write(NOTE)
    f.write('''
#ifndef _CGLMACRO_H
#define _CGLMACRO_H

#ifdef __gl3_h_
#  ifndef __has_feature
#    define __has_feature(X) 0
#  endif
#  if !__has_feature(modules)
#    error CGLMacro.h cannot be used together with gl3.h
#  endif
#endif

#include <OpenGL/CGLTypes.h>
#include <OpenGL/CGLContext.h>
#include <OpenGL/gl.h>
#include <OpenGL/glext.h>

/* The names of the context and renderer variables the macros use. */
#if !defined(CGL_MACRO_CONTEXT)
#define CGL_MACRO_CONTEXT cgl_ctx
#endif
#if !defined(CGL_MACRO_RENDERER)
#define CGL_MACRO_RENDERER cgl_rend
#endif

#define CGL_MACRO_DECLARE_CONTEXT() CGLContextObj CGL_MACRO_CONTEXT = CGLGetCurrentContext();

/* With CGL_MACRO_CACHE_RENDERER defined, the renderer is read once into a
   local variable instead of before every call. */
#if defined(CGL_MACRO_CACHE_RENDERER)
#define CGL_MACRO_DECLARE_RENDERER() GLIContext CGL_MACRO_RENDERER = CGL_MACRO_CONTEXT->rend;
#define CGL_MACRO_CONTEXT_RENDERER CGL_MACRO_RENDERER
#else
#define CGL_MACRO_DECLARE_RENDERER()
#define CGL_MACRO_CONTEXT_RENDERER CGL_MACRO_CONTEXT->rend
#endif

#define CGL_MACRO_DECLARE_VARIABLES() \\
    CGL_MACRO_DECLARE_CONTEXT(); \\
    CGL_MACRO_DECLARE_RENDERER();

/* Converts an object handle to the ARB handle type. */
#define CGL_HANDLE_ARB(handle) (GLhandleARB)((unsigned long) handle)

''')
    for kind, name, target, names, cast in macros:
        if kind == 'F':
            args = names.split(',') if names else []
            call = '(*(CGL_MACRO_CONTEXT)->disp.%s)(CGL_MACRO_CONTEXT_RENDERER%s)' % (
                target, ''.join(', ' + a for a in args))
            if cast:
                call = '(%s)((unsigned long) %s)' % (cast, call)
            f.write('#define %s(%s) \\\n    %s\n' % (name, ', '.join(args), call))
        else:
            f.write('#define %s %s\n' % (name, target))
    f.write('\n#endif /* _CGLMACRO_H */\n')

# ---- gli_thunks.inc
names_of = {}
for kind, name, target, names, cast in macros:
    if kind == 'F':
        names_of.setdefault(target, []).append((cast != '', name))
with open(os.path.join(root, 'gli_thunks.inc'), 'w') as f:
    f.write(NOTE)
    f.write('/* One function per dispatch slot: makes the context current on the calling\n'
            '   thread, then calls the host function the slot stands for. */\n\n')
    f.write('#define GLI_SLOT_COUNT %d\n\n' % len(slots))
    for i, (name, ret, plist) in enumerate(slots):
        pdecl = ', '.join(['GLIContext rend'] + decl_params(plist, False))
        ptypes = ', '.join([p[0] for p in plist]) or 'void'
        pnames = ', '.join('a%d' % k for k in range(len(plist)))
        f.write('static %s gli_%s(%s) {\n' % (ret, name, pdecl))
        void = ret.strip() == 'void'
        f.write('    int acquired = gli_enter(rend);\n')
        call = '((%s (*)(%s)) gli_host(%d))(%s)' % (ret, ptypes, i, pnames)
        f.write('    %s%s;\n' % ('' if void else '%s result = ' % ret, call))
        f.write('    if (acquired == 2)\n        gl_release_transient();\n')
        f.write('%s}\n' % ('' if void else '    return result;\n'))
    f.write('\nstatic const char *const gli_host_names[GLI_SLOT_COUNT][4] = {\n')
    for name, ret, plist in slots:
        ns = [n for casted, n in sorted(names_of.get(name, []), key=lambda x: x[0])][:3]
        f.write('    { %s },\n' % ', '.join(['"%s"' % n for n in ns] + ['NULL']))
    f.write('};\n\nstatic void *const gli_template[GLI_SLOT_COUNT] = {\n')
    for name, ret, plist in slots:
        f.write('    (void *) gli_%s,\n' % name)
    f.write('};\n')
print('generated', len(slots), 'slots')
