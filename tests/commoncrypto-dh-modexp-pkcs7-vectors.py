#!/usr/bin/env python3
# Writes tests/src/commoncrypto_dh_modexp_pkcs7_vectors.h for
# tests/src/commoncrypto_dh_modexp_pkcs7.c. Needs pyca/cryptography.
#
# Every expected value comes from an implementation independent of Darling:
# - modular exponentiation: Python's built-in pow();
# - DH: the RFC 2409 group 2 and RFC 3526 group 5 primes are derived from
#   their defining formula (p = 2^n - 2^(n-64) - 1 + 2^64 * (floor(2^(n-130) pi) + k),
#   pi by Machin's formula) and the peer public key is pow(2, b, p);
# - PKCS #7 (RFC 5652 section 6.3) ciphertexts: pyca/cryptography (OpenSSL).
#   The AES-128 key, IV and the start of the plaintext are those of
#   NIST SP 800-38A appendix F.2.1, whose CBC ciphertext the first four
#   blocks of the 64-byte case reproduce.
#
# usage: tests/commoncrypto-dh-modexp-pkcs7-vectors.py > tests/src/commoncrypto_dh_modexp_pkcs7_vectors.h

import random

from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes
try:
    from cryptography.hazmat.decrepit.ciphers.algorithms import TripleDES
except ImportError:
    TripleDES = algorithms.TripleDES


def pi_times_power_of_two(bits):
    guard = 64
    one = 1 << (bits + guard)

    def arctan_of_inverse(x):
        term = one // x
        total = term
        k = 1
        while term:
            term //= x * x
            part = term // (2 * k + 1)
            total += -part if k % 2 else part
            k += 1
        return total

    return (16 * arctan_of_inverse(5) - 4 * arctan_of_inverse(239)) >> guard


def modp_prime(bits, k):
    return 2**bits - 2**(bits - 64) - 1 + 2**64 * (pi_times_power_of_two(bits - 130) + k)


def hexstr(v):
    h = '%x' % v
    return h if len(h) % 2 == 0 else '0' + h


def c_bytes(data):
    if not data:
        return '{ 0 }'
    return '{ ' + ', '.join('0x%02x' % b for b in data) + ' }'


rng = random.Random(5652)
out = []
w = out.append

w('/* Generated by tests/commoncrypto-dh-modexp-pkcs7-vectors.py; do not edit. */\n')

# ---- modular exponentiation: base, exponent, modulus, expected (hex, big-endian)
cases = [
    ('exponent 0', 3, 0, 11),
    ('0^0 mod 7', 0, 0, 7),
    ('0^5 mod 7', 0, 5, 7),
    ('modulus 1', 5, 3, 1),
    ('modulus 1, exponent 0', 5, 0, 1),
    ('modulus 2', 7, 3, 2),
    ('even modulus 1000', 2, 10, 1000),
    ('modulus 2^64', 3, 2**64 - 1, 2**64),
    ('base above modulus', 2**200 + 12345, 65537, 2**127 - 1),
    ('base equal to modulus', 2**127 - 1, 3, 2**127 - 1),
    ('exponent above modulus', 7, 2**300 + 1, 2**61 - 1),
]
# random sizes, odd and even moduli
for bits_m, bits_e, bits_b, odd in [(64, 64, 64, True), (521, 521, 600, True), (1024, 160, 1024, True),
                                    (2048, 2048, 3000, True), (4096, 4096, 4096, True),
                                    (1024, 1024, 1024, False), (2048, 256, 2048, False),
                                    (3072, 64, 1500, False)]:
    m = rng.getrandbits(bits_m) | (1 << (bits_m - 1))
    m = m | 1 if odd else m & ~1
    e = rng.getrandbits(bits_e) | (1 << (bits_e - 1))
    b = rng.getrandbits(bits_b)
    cases.append(('random %d-bit %s modulus, %d-bit exponent' % (bits_m, 'odd' if odd else 'even', bits_e), b, e, m))
# a DH-shaped case on the RFC 3526 group 5 prime
p5 = modp_prime(1536, 741804)
cases.append(('2^x mod the RFC 3526 group 5 prime', 2, rng.getrandbits(1535), p5))

w('struct modexp_vector { const char *name, *base, *exponent, *modulus, *result; };\n')
w('static const struct modexp_vector modexp_vectors[] = {\n')
for name, b, e, m in cases:
    w('\t{ "%s", "%s", "%s", "%s", "%s" },\n' % (name, hexstr(b), hexstr(e), hexstr(m), hexstr(pow(b, e, m))))
w('};\n\n')

# ---- DH: the group primes and a peer key pow(2, b, p) with b known
for name, bits, k in [('group2', 1024, 129093), ('group5', 1536, 741804)]:
    p = modp_prime(bits, k)
    b = rng.getrandbits(bits - 2) | 1
    w('/* %s: %d-bit MODP prime; peer_private is b, peer_public is 2^b mod p */\n' % (name, bits))
    w('static const char dh_%s_prime[] = "%s";\n' % (name, hexstr(p)))
    w('static const char dh_%s_peer_private[] = "%s";\n' % (name, hexstr(b)))
    w('static const char dh_%s_peer_public[] = "%s";\n\n' % (name, hexstr(pow(2, b, p))))

# ---- PKCS #7
aes_key = bytes.fromhex('2b7e151628aed2a6abf7158809cf4f3c')
aes_iv = bytes(range(16))
sp800_38a_plain = bytes.fromhex('6bc1bee22e409f96e93d7e117393172aae2d8a571e03ac9c9eb76fac45af8e51'
                                '30c81c46a35ce411e5fbc1191a0a52eff69f2445df4f9b17ad2b417be66c3710')
sp800_38a_cbc = bytes.fromhex('7649abac8119b246cee98e9b12e9197d5086cb9b507219ee95db113a917678b2'
                              '73bed6b8e3c1743b7116e69e222295163ff1caa1681fac09120eca307586e1a7')
des3_key = bytes(range(0x40, 0x58))
des3_iv = bytes(range(0xa0, 0xa8))
plain = sp800_38a_plain


def padded(data, size):
    k = size - len(data) % size
    return data + bytes([k]) * k


def encrypt(alg, mode, data):
    e = Cipher(alg, mode).encryptor()
    return e.update(data) + e.finalize()


assert encrypt(algorithms.AES(aes_key), modes.CBC(aes_iv), plain) == sp800_38a_cbc

w('static const uint8_t aes_key[16] = %s;\n' % c_bytes(aes_key))
w('static const uint8_t aes_iv[16] = %s;\n' % c_bytes(aes_iv))
w('static const uint8_t des3_key[24] = %s;\n' % c_bytes(des3_key))
w('static const uint8_t des3_iv[8] = %s;\n' % c_bytes(des3_iv))
w('static const uint8_t pkcs7_plain[64] = %s;\n\n' % c_bytes(plain))
w('struct pkcs7_vector { size_t length; size_t cipher_length; const uint8_t *cipher; };\n')

for label, alg, mode_of, size, top in [('aes_cbc', algorithms.AES(aes_key), lambda: modes.CBC(aes_iv), 16, 33),
                                       ('aes_ecb', algorithms.AES(aes_key), lambda: modes.ECB(), 16, 33),
                                       ('des3_cbc', TripleDES(des3_key), lambda: modes.CBC(des3_iv), 8, 17)]:
    for n in range(top + 1):
        c = encrypt(alg, mode_of(), padded(plain[:n], size))
        w('static const uint8_t %s_%d[] = %s;\n' % (label, n, c_bytes(c)))
    w('static const struct pkcs7_vector %s_vectors[] = {\n' % label)
    for n in range(top + 1):
        w('\t{ %d, sizeof(%s_%d), %s_%d },\n' % (n, label, n, label, n))
    w('};\n\n')

# The 64-byte AES-CBC case is SP 800-38A F.2.1 plus one block of padding.
w('static const uint8_t sp800_38a_cbc[64] = %s;\n\n' % c_bytes(sp800_38a_cbc))

# Two-block AES-CBC ciphertexts whose second plaintext block is given as is
# (no padding added by the encryptor), to test how decryption treats it.
second_blocks = [
    ('last byte 0', bytes(15) + b'\x00'),
    ('last byte 17', bytes(15) + b'\x11'),
    ('last byte 255', bytes(15) + b'\xff'),
    ('1 then 2', bytes(14) + b'\x01\x02'),
    ('3 with a 4 inside', bytes(13) + b'\x04\x03\x03'),
    ('16 with one 15', b'\x0f' + b'\x10' * 15),
    ('valid 1', bytes(15) + b'\x01'),
    ('valid 5', bytes(11) + b'\x05' * 5),
    ('valid full block', b'\x10' * 16),
]
# dropped: what macOS drops (see the QUIRK in the test): the last byte k when 1 <= k <= 16, else nothing
w('struct raw_padding_vector { const char *name; int valid; size_t dropped; uint8_t cipher[32]; };\n')
w('static const struct raw_padding_vector raw_padding_vectors[] = {\n')
for name, block in second_blocks:
    k = block[-1]
    valid = 1 <= k <= 16 and block[-k:] == bytes([k]) * k
    c = encrypt(algorithms.AES(aes_key), modes.CBC(aes_iv), plain[:16] + block)
    w('\t{ "%s", %d, %d, %s },\n' % (name, valid, k if 1 <= k <= 16 else 0, c_bytes(c)))
w('};\n')

print(''.join(out), end='')
