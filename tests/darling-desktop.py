"""Host-side tests for the desktop integration (src/desktop-integration).

Usage: darling-desktop.py <script> <mime xml> <binary desktop> <bundle desktop> <install prefix>

Builds a small prefix with two app bundles and a CoreTypes UTI database, runs darling-desktop on it,
and checks the generated entries against the Desktop Entry specification. Where the host has the
freedesktop.org tools, the shared-mime-info package and all desktop entries are validated too.
"""
import os
from pathlib import Path
import plistlib
import shutil
import subprocess
import sys
import tempfile
import unittest
import xml.etree.ElementTree as ET

SCRIPT = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else None
MIME_XML = Path(sys.argv[2]).resolve() if len(sys.argv) > 2 else None
DESKTOPS = [Path(path).resolve() for path in sys.argv[3:5]] if len(sys.argv) > 4 else []
PREFIX = sys.argv[5] if len(sys.argv) > 5 else None


def desktop_exec_args(value):
    """Splits an Exec value as the Desktop Entry specification quotes it."""
    args, cur, quoted, escaped, started = [], "", False, False, False
    i = 0
    while i < len(value):
        ch = value[i]
        if escaped:
            cur += ch
            escaped = False
        elif ch == "%" and i + 1 < len(value) and value[i + 1] == "%":
            cur += "%"
            i += 1
        elif quoted and ch == "\\":
            escaped = True
        elif ch == '"':
            quoted = not quoted
            started = True
        elif ch == " " and not quoted:
            if started or cur:
                args.append(cur)
            cur, started = "", False
        else:
            cur += ch
        i += 1
    if started or cur:
        args.append(cur)
    return args


def entry_values(path):
    values = {}
    for line in path.read_text().splitlines():
        if not line.startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            values[key] = value
    return values


class DesktopIntegration(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.tmp = tempfile.TemporaryDirectory(prefix="darling-desktop-test-")
        cls.root = Path(cls.tmp.name)
        cls.prefix = cls.root / "prefix"
        cls.output = cls.root / "applications"
        cls.app_dir = cls.prefix / "libexec/darling/Applications"
        cls.core_types = cls.prefix / "libexec/darling/System/Library/CoreServices/CoreTypes.bundle/Contents/Info.plist"
        cls.core_types.parent.mkdir(parents=True)
        cls.app_dir.mkdir(parents=True)

        declarations = [
            {"UTTypeIdentifier": "public.item"},
            {"UTTypeIdentifier": "public.data", "UTTypeConformsTo": ["public.item"]},
            {"UTTypeIdentifier": "public.text", "UTTypeConformsTo": ["public.data"]},
            {"UTTypeIdentifier": "public.plain-text", "UTTypeConformsTo": ["public.text"],
             "UTTypeTagSpecification": {"public.filename-extension": ["txt"], "public.mime-type": ["text/plain"]}},
            {"UTTypeIdentifier": "public.rtf", "UTTypeConformsTo": ["public.text"],
             "UTTypeTagSpecification": {"public.filename-extension": ["rtf"], "public.mime-type": ["text/rtf", "application/rtf"]}},
            {"UTTypeIdentifier": "com.example.thing", "UTTypeConformsTo": ["public.data"],
             "UTTypeTagSpecification": {"public.filename-extension": ["thing"], "public.mime-type": ["application/x-thing"]}},
        ]
        with open(cls.core_types, "wb") as fp:
            plistlib.dump({"UTExportedTypeDeclarations": declarations}, fp)

        text_edit = cls.app_dir / "TextEdit.app/Contents"
        text_edit.mkdir(parents=True)
        with open(text_edit / "Info.plist", "wb") as fp:
            plistlib.dump({
                "CFBundleDisplayName": "TextEdit",
                "CFBundleIdentifier": "com.apple.TextEdit",
                "CFBundleDocumentTypes": [
                    {"LSItemContentTypes": ["public.rtf"]},
                    {"LSItemContentTypes": ["public.text"]},
                    {"LSItemContentTypes": ["public.data"]},
                ],
            }, fp)

        thing_viewer = cls.app_dir / "Thing Viewer.app/Contents"
        thing_viewer.mkdir(parents=True)
        with open(thing_viewer / "Info.plist", "wb") as fp:
            plistlib.dump({
                "CFBundleName": "Thing Viewer",
                "CFBundleDocumentTypes": [{"CFBundleTypeExtensions": ["thing"]}],
            }, fp)

        # An entry from an earlier run must not survive when its application is gone.
        cls.output.mkdir()
        stale = cls.output / "darling-Stale.desktop"
        stale.write_text("# Generated by darling-desktop; changes will be overwritten.\n[Desktop Entry]\n")

        result = subprocess.run([str(SCRIPT), "--prefix", str(cls.prefix), "--output-dir", str(cls.output),
                                 "--core-types", str(cls.core_types)],
                                stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True)
        if result.returncode != 0:
            raise RuntimeError("darling-desktop failed:\n" + result.stdout)
        cls.entries = [entry_values(path) for path in sorted(cls.output.glob("*.desktop"))]

    @classmethod
    def tearDownClass(cls):
        cls.tmp.cleanup()

    def by_name(self, name):
        for entry in self.entries:
            if entry.get("Name") == name:
                return entry
        self.fail(f"no desktop entry named {name}: {self.entries}")

    def test_generated_entries(self):
        self.assertEqual(len(self.entries), 2, self.entries)
        self.assertFalse((self.output / "darling-Stale.desktop").exists())

        text_edit = self.by_name("TextEdit")
        self.assertEqual(desktop_exec_args(text_edit["Exec"]),
                         [str(self.prefix / "bin/darling"), "open", "-a", "TextEdit", "%F"])
        mime_types = text_edit["MimeType"].strip(";").split(";")
        self.assertIn("text/plain", mime_types)
        self.assertIn("text/rtf", mime_types)
        self.assertIn("application/rtf", mime_types)
        # public.data was also declared; it must not make TextEdit the handler for every file.
        self.assertNotIn("application/octet-stream", mime_types)

        viewer = self.by_name("Thing Viewer")
        self.assertEqual(desktop_exec_args(viewer["Exec"]),
                         [str(self.prefix / "bin/darling"), "open", "-a", "Thing Viewer", "%F"])
        self.assertEqual(viewer["MimeType"], "application/x-thing;")

    def test_generic_entries(self):
        self.assertEqual(len(DESKTOPS), 2)
        binary = entry_values(DESKTOPS[0])
        bundle = entry_values(DESKTOPS[1])
        self.assertEqual(binary["MimeType"], "application/x-mach-binary;")
        self.assertEqual(desktop_exec_args(binary["Exec"]), [PREFIX + "/bin/darling", "%f"])
        self.assertEqual(bundle["MimeType"], "application/x-apple-app-bundle;")
        self.assertEqual(desktop_exec_args(bundle["Exec"]), [PREFIX + "/bin/darling", "open", "%f"])

    def test_desktop_files_validate(self):
        validator = shutil.which("desktop-file-validate")
        if validator is None:
            self.skipTest("no desktop-file-validate")
        paths = list(self.output.glob("*.desktop")) + DESKTOPS
        for path in paths:
            result = subprocess.run([validator, str(path)], stdout=subprocess.PIPE,
                                    stderr=subprocess.STDOUT, text=True)
            self.assertEqual(result.returncode, 0, f"{path}: {result.stdout}")
            self.assertNotIn("error", result.stdout, f"{path}: {result.stdout}")

    def test_mime_xml(self):
        root = ET.parse(MIME_XML).getroot()
        self.assertEqual(root.tag, "{http://www.freedesktop.org/standards/shared-mime-info}mime-info")
        types = {element.attrib["type"] for element in root}
        self.assertIn("application/x-mach-binary", types)
        self.assertIn("application/x-apple-app-bundle", types)

        if shutil.which("update-mime-database") is None:
            return
        mime_root = self.root / "mime"
        packages = mime_root / "packages"
        packages.mkdir(parents=True)
        shutil.copy(MIME_XML, packages)
        subprocess.run(["update-mime-database", str(mime_root)], check=True,
                       stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
        globs = (mime_root / "globs2").read_text()
        self.assertIn(":application/x-mach-binary:*.dylib", globs)
        self.assertIn(":application/x-apple-app-bundle:*.app", globs)


if __name__ == "__main__":
    if any(item is None for item in (SCRIPT, MIME_XML, PREFIX)) or len(DESKTOPS) != 2:
        sys.exit(__doc__)
    unittest.main(argv=sys.argv[:1])
