static void writeFile(const char* path)
{
	int fd = open(path, O_WRONLY | O_CREAT | O_TRUNC, 0644);

	if (fd < 0 || write(fd, kResourceFile, sizeof(kResourceFile)) != (ssize_t) sizeof(kResourceFile))
		printf("FAIL: cannot write %s\n", path), g_failures++;
	if (fd >= 0)
		close(fd);
}

int main(void)
{
	// Blocks and handles report the size that was asked for, not the size the allocator rounded it up to
	Ptr p = NewPtr(5);
	CHECK(p && GetPtrSize(p) == 5);
	Ptr pc = NewPtrClear(7);
	CHECK(pc && GetPtrSize(pc) == 7 && pc[6] == 0);
	Handle h = NewHandle(5);
	CHECK(h && GetHandleSize(h) == 5);
	Handle hc = NewHandleClear(21);
	CHECK(hc && GetHandleSize(hc) == 21);
	Handle zero = NewHandle(0);
	CHECK(zero && GetHandleSize(zero) == 0);
	Handle empty = NewEmptyHandle();
	CHECK(empty && GetHandleSize(empty) == 0);

	SetHandleSize(h, 3);
	CHECK(GetHandleSize(h) == 3);
	SetHandleSize(h, 40);
	CHECK(GetHandleSize(h) == 40);
	SetHandleSize(h, 0);
	CHECK(GetHandleSize(h) == 0);

	Handle copy = NULL;
	CHECK(PtrToHand("abcde", &copy, 5) == noErr && GetHandleSize(copy) == 5);
	CHECK(HandToHand(&copy) == noErr && GetHandleSize(copy) == 5);
	CHECK(PtrAndHand("xyz", copy, 3) == noErr && GetHandleSize(copy) == 8 && memcmp(*copy, "abcdexyz", 8) == 0);

	// a resource of 5 bytes is a handle of 5 bytes
	char dir[] = "/tmp/hsizeXXXXXX";
	CHECK(mkdtemp(dir) != NULL);
	char path[256];
	snprintf(path, sizeof(path), "%s/res.rsrc", dir);
	writeFile(path);

	FSRef ref;
	ResFileRefNum refNum = 0;
	OSStatus err = FSPathMakeRef((const UInt8*) path, &ref, NULL);
	CHECK(err == noErr);
	HFSUniStr255 dataFork;
	CHECK(FSGetDataForkName(&dataFork) == noErr);
	err = FSOpenResourceFile(&ref, dataFork.length, dataFork.unicode, fsRdPerm, &refNum);
	CHECK(err == noErr);
	UseResFile(refNum);
	Handle res = Get1Resource('TEST', 128);
	CHECK(res != NULL);
	if (res)
	{
		CHECK(GetHandleSize(res) == 5);
		CHECK(memcmp(*res, "hello", 5) == 0);
	}
	CloseResFile(refNum);
	unlink(path);
	rmdir(dir);

	DisposePtr(p);
	DisposePtr(pc);
	DisposeHandle(h);
	DisposeHandle(hc);
	DisposeHandle(zero);
	DisposeHandle(empty);
	DisposeHandle(copy);

	printf(g_failures ? "FAILED: %d\n" : "PASS\n", g_failures);
	return g_failures != 0;
}
