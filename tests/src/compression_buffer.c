static size_t input(uint8_t *buf) {
    size_t n = 0;
    for (int i = 0; i < 300; i++)
        n += sprintf((char *) buf + n, "line %d of the compression test input\n", i);
    return n;
}

static void check_algorithm(const char *name, compression_algorithm algorithm, const uint8_t *vector, size_t vectorSize,
                            const uint8_t *in, size_t n) {
    static uint8_t out[20000], back[20000];
    fprintf(stderr, "%s\n", name);
    size_t got = compression_decode_buffer(back, sizeof back, vector, vectorSize, NULL, algorithm);
    CHECK(got == n);
    CHECK(got == n && memcmp(back, in, n) == 0);

    size_t encoded = compression_encode_buffer(out, sizeof out, in, n, NULL, algorithm);
    CHECK(encoded > 0 && encoded < n);
    memset(back, 0, sizeof back);
    got = compression_decode_buffer(back, sizeof back, out, encoded, NULL, algorithm);
    CHECK(got == n && memcmp(back, in, n) == 0);

    memset(back, 0, sizeof back);
    CHECK(compression_decode_buffer(back, 100, vector, vectorSize, NULL, algorithm) == 100);
    CHECK(memcmp(back, in, 100) == 0);
    CHECK(compression_encode_buffer(out, 10, in, n, NULL, algorithm) == 0);

    uint8_t garbage[64];
    memset(garbage, 0xab, sizeof garbage);
    CHECK(compression_decode_buffer(back, sizeof back, garbage, sizeof garbage, NULL, algorithm) == 0);

    encoded = compression_encode_buffer(out, sizeof out, in, 0, NULL, algorithm);
    CHECK(encoded > 0);
    CHECK(compression_decode_buffer(back, sizeof back, out, encoded, NULL, algorithm) == 0);
}

int main(void) {
    static uint8_t in[20000];
    size_t n = input(in);
    check_algorithm("lzfse", COMPRESSION_LZFSE, lzfse_vector, sizeof lzfse_vector, in, n);
    check_algorithm("zlib", COMPRESSION_ZLIB, zlib_vector, sizeof zlib_vector, in, n);

    size_t encodeScratch = compression_encode_scratch_buffer_size(COMPRESSION_LZFSE);
    size_t decodeScratch = compression_decode_scratch_buffer_size(COMPRESSION_LZFSE);
    CHECK(encodeScratch > 0 && decodeScratch > 0);
    void *scratch = malloc(encodeScratch > decodeScratch ? encodeScratch : decodeScratch);
    static uint8_t out[20000], back[20000];
    size_t encoded = compression_encode_buffer(out, sizeof out, in, n, scratch, COMPRESSION_LZFSE);
    CHECK(compression_decode_buffer(back, sizeof back, out, encoded, scratch, COMPRESSION_LZFSE) == n);
    free(scratch);

    if (failures == 0)
        printf("PASS compression_buffer\n");
    return failures != 0;
}
