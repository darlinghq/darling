static uint8_t *input_a(size_t *length) {
    uint8_t *data = malloc(1800);
    for (int i = 0; i < 100; i++)
        memcpy(data + i * 18, "hello hello hello ", 18);
    *length = 1800;
    return data;
}

static uint8_t *input_b(size_t *length) {
    uint8_t *data = malloc(140000);
    for (int i = 0; i < 140000; i++)
        data[i] = (uint8_t) ((i / 1024) * 37);
    *length = 140000;
    return data;
}

static void check_algorithm(compression_algorithm algorithm, const char *name, const uint8_t *vec_a, size_t vec_a_size, const uint8_t *vec_b, size_t vec_b_size) {
    size_t a_size, b_size;
    uint8_t *a = input_a(&a_size), *b = input_b(&b_size);
    uint8_t *out = malloc(200000), *packed = malloc(200000), *small = malloc(64);

    // macOS streams decode to the inputs
    CHECK(compression_decode_buffer(out, 200000, vec_a, vec_a_size, NULL, algorithm) == a_size && memcmp(out, a, a_size) == 0);
    CHECK(compression_decode_buffer(out, 200000, vec_b, vec_b_size, NULL, algorithm) == b_size && memcmp(out, b, b_size) == 0);
    // into a buffer that is too small: it is filled and its size returned
    if (algorithm == COMPRESSION_LZMA) {
        CHECK(compression_decode_buffer(small, 64, vec_a, vec_a_size, NULL, algorithm) == 0);
        CHECK(compression_decode_buffer(out, 70000, vec_b, vec_b_size, NULL, algorithm) == 0);
        CHECK(compression_decode_buffer(out, b_size - 1, vec_b, vec_b_size, NULL, algorithm) == 0);
        CHECK(compression_decode_buffer(out, b_size, vec_b, vec_b_size, NULL, algorithm) == b_size);
    } else {
        CHECK(compression_decode_buffer(small, 64, vec_a, vec_a_size, NULL, algorithm) == 64 && memcmp(small, a, 64) == 0);
        CHECK(compression_decode_buffer(out, 70000, vec_b, vec_b_size, NULL, algorithm) == 70000 && memcmp(out, b, 70000) == 0);
    }

    // our streams decode to the inputs
    size_t n = compression_encode_buffer(packed, 200000, a, a_size, NULL, algorithm);
    CHECK(n > 0 && n < a_size);
    CHECK(compression_decode_buffer(out, 200000, packed, n, NULL, algorithm) == a_size && memcmp(out, a, a_size) == 0);
    n = compression_encode_buffer(packed, 200000, b, b_size, NULL, algorithm);
    CHECK(n > 0 && n < b_size / 10);
    CHECK(compression_decode_buffer(out, 200000, packed, n, NULL, algorithm) == b_size && memcmp(out, b, b_size) == 0);
    // encoding into a buffer that is too small
    CHECK(compression_encode_buffer(small, 8, a, a_size, NULL, algorithm) == 0);

    // random bytes: the stream decodes back, and does not shrink
    uint8_t *random = malloc(300);
    uint32_t state = 2463534242u;
    for (int i = 0; i < 300; i++) {
        state ^= state << 13;
        state ^= state >> 17;
        state ^= state << 5;
        random[i] = (uint8_t) (state >> 11);
    }
    n = compression_encode_buffer(packed, 200000, random, 300, NULL, algorithm);
    CHECK(n >= 300);
    CHECK(compression_decode_buffer(out, 200000, packed, n, NULL, algorithm) == 300 && memcmp(out, random, 300) == 0);

    // invalid, truncated and empty input decode to nothing
    memset(packed, 0xff, 64);
    CHECK(compression_decode_buffer(out, 200000, packed, 64, NULL, algorithm) == 0);
    CHECK(compression_decode_buffer(out, 200000, vec_b, vec_b_size / 2, NULL, algorithm) == 0);
    CHECK(compression_decode_buffer(out, 200000, vec_b, 0, NULL, algorithm) == 0);
    // no input encodes to a stream that decodes to nothing
    n = compression_encode_buffer(packed, 200000, a, 0, NULL, algorithm);
    CHECK(n > 0);
    CHECK(compression_decode_buffer(out, 200000, packed, n, NULL, algorithm) == 0);
    (void) name;
    free(a); free(b); free(out); free(packed); free(small); free(random);
}

int main(void) {
    check_algorithm(COMPRESSION_LZ4, "LZ4", vec_a_lz4, sizeof vec_a_lz4, vec_b_lz4, sizeof vec_b_lz4);
    check_algorithm(COMPRESSION_LZMA, "LZMA", vec_a_lzma, sizeof vec_a_lzma, vec_b_lzma, sizeof vec_b_lzma);

    // LZ4 framing as macOS writes it
    size_t b_size;
    uint8_t *b = input_b(&b_size);
    uint8_t *packed = malloc(200000);
    size_t n = compression_encode_buffer(packed, 200000, b, b_size, NULL, COMPRESSION_LZ4);
    CHECK(n > 16 && memcmp(packed, "bv41", 4) == 0);
    CHECK(packed[4] == 0 && packed[5] == 0 && packed[6] == 1 && packed[7] == 0);   // 65536 bytes in the first block
    CHECK(memcmp(packed + n - 4, "bv4$", 4) == 0);
    n = compression_encode_buffer(packed, 200000, b, 0, NULL, COMPRESSION_LZ4);
    CHECK(n == 4 && memcmp(packed, "bv4$", 4) == 0);
    uint8_t empty_block[12] = {'b', 'v', '4', '-', 0, 0, 0, 0, 'b', 'v', '4', '$'};
    uint8_t out[16];
    CHECK(compression_decode_buffer(out, 16, empty_block, 12, NULL, COMPRESSION_LZ4) == 0);
    // a stored block decodes
    uint8_t stored[16] = {'b', 'v', '4', '-', 3, 0, 0, 0, 'a', 'b', 'c', 'b', 'v', '4', '$'};
    CHECK(compression_decode_buffer(out, 16, stored, 15, NULL, COMPRESSION_LZ4) == 3 && memcmp(out, "abc", 3) == 0);
    free(b); free(packed);

    // the .xz stream written for LZMA: magic, stream flags 0 (no check)
    uint8_t xz[64];
    n = compression_encode_buffer(xz, 64, (const uint8_t *) "hello world", 11, NULL, COMPRESSION_LZMA);
    CHECK(n > 12 && memcmp(xz, "\xfd" "7zXZ\x00\x00\x00", 8) == 0);

    printf(failures ? "%d failure(s)\n" : "PASS\n", failures);
    return failures != 0;
}
