static void positive(const unsigned char *data, size_t length,
                     unsigned format, unsigned channels,
                     unsigned rate, unsigned seed, int file)
{
    (void)file;
    unsigned before = failures;
    unsigned char pcm[400];
    struct qt_mov_pcm_info info;

    memset(pcm, 0x5a, sizeof(pcm));
    memset(&info, 0xa5, sizeof(info));

    int status = qt_mov_extract_pcm(
        data, length, pcm, sizeof(pcm), &info);

    CHECK(status == QT_MOV_PCM_OK);

    if (status == QT_MOV_PCM_OK) {
        CHECK(info.format == format);
        CHECK(info.channels == channels);
        CHECK(info.sample_rate == rate);
        CHECK(info.bits_per_sample == 16);
        CHECK(info.frame_count == 100);
        CHECK(info.byte_count == 200 * channels);
        verify_pcm_bytes(pcm, 0, 200 * channels, seed);

        memset(pcm, 0x5a, sizeof(pcm));
        struct qt_mov_pcm_info snapshot;
        memcpy(&snapshot, &info, sizeof(info));

        CHECK(qt_mov_extract_pcm(
            data, length, pcm, 200 * channels - 1, &info)
            == QT_MOV_PCM_BUFFER_TOO_SMALL);

        CHECK(memcmp(&snapshot, &info, sizeof(info)) == 0);

        for (unsigned i = 0; i < sizeof(pcm); ++i)
            CHECK(pcm[i] == 0x5a);
    }

    if (failures == before)
        ++good;
}

