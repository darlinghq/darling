static void mutate(unsigned char *p, size_t offset,
                   unsigned width, uint64_t value)
{
    for (unsigned i = 0; i < width; ++i) {
        p[offset + width - 1 - i] = (unsigned char)value;
        value >>= 8;
    }
}
