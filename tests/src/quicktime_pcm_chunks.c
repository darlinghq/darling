static unsigned checks, failures, good, rejected;

#define CHECK(x) do { ++checks; if (!(x)) { \
    ++failures; printf("FAIL %d %s\n",__LINE__,#x); \
} } while (0)

static void verify_pcm_bytes(const unsigned char *p, unsigned first,
                             unsigned count, unsigned seed)
{
    for (unsigned i = 0; i < count; ++i) {
        unsigned j = first + i;
        CHECK(p[i] == ((j * 29 + seed + (j >> 4)) & 255));
    }
}

