static OSErr import_movie(const unsigned char *data, size_t length,
                          Movie *movie, int file)
{
    if (!file) {
        unsigned char *copy = malloc(length);
        if (!copy)
            return memFullErr;

        memcpy(copy, data, length);

        PointerDataRefRecord record = { copy, (Size)length };
        PointerDataRefPtr p = &record;

        OSErr error = NewMovieFromDataRef(
            movie, 0, NULL, (Handle)&p, PointerDataHandlerSubType);

        memset(copy, 0xa5, length);
        free(copy);
        return error;
    }

    char path[] = "/tmp/qt-up11-XXXXXX";
    int fd = mkstemp(path);

    if (fd < 0)
        return ioErr;

    ssize_t written = write(fd, data, length);
    close(fd);

    FSRef ref;
    short fork = -1;
    OSErr error = ioErr;

    if (written == (ssize_t)length) {
        error = FSPathMakeRef((const UInt8 *)path, &ref, NULL);

        if (error == noErr)
            error = FSOpenFork(&ref, 0, NULL, fsRdPerm, &fork);

        if (error == noErr) {
            error = NewMovieFromFile(
                movie, fork, NULL, NULL, 0, NULL);
            FSCloseFork(fork);
        }
    }

    unlink(path);
    return error;
}

static void read_samples(Media media, Handle data,
                         unsigned start, unsigned n,
                         unsigned channels, unsigned seed,
                         SInt32 limit, SInt32 requested)
{
    TimeValue time = -1, duration = -1;
    SInt32 bytes = -1, samples = -1, index = -1;
    SInt16 flags = -1;

    OSErr error = GetMediaSample(
        media, data, limit, &bytes, start, &time, &duration,
        NULL, &index, requested, &samples, &flags);

    CHECK(error == noErr);

    if (error != noErr)
        return;

    unsigned expected = n * channels * 2;

    CHECK(bytes == (SInt32)expected);
    CHECK(samples == (SInt32)n);
    CHECK(time == (TimeValue)start);
    CHECK(duration == 1);
    CHECK(index == 1);
    CHECK(flags == 0);

    long size = GetHandleSize(data);

    CHECK(size == (long)expected);

    if (*data && size == (long)expected)
        verify_pcm_bytes((const unsigned char *)*data,
                         start * channels * 2, expected, seed);
}

static void positive(const unsigned char *data, size_t length,
                     unsigned format, unsigned channels,
                     unsigned rate, unsigned seed, int file)
{
    unsigned before = failures;
    Movie m = NULL;

    CHECK(import_movie(data, length, &m, file) == noErr);
    CHECK(m != NULL);

    if (!m)
        return;

    Media media = GetTrackMedia(GetMovieIndTrack(m, 1));

    CHECK(media != NULL);
    CHECK(GetMediaSampleCount(media) == 100);
    CHECK(GetMediaTimeScale(media) == (TimeScale)rate);
    CHECK(GetMediaSampleDescriptionCount(media) == 1);
    CHECK(GetMediaDuration(media) == 100);

    Handle pcm = NewHandle(1);
    Handle desc = NewHandle(1);

    CHECK(pcm != NULL && desc != NULL);

    if (pcm && desc) {
        GetMediaSampleDescription(
            media, 1, (SampleDescriptionHandle)desc);

        CHECK(GetMoviesError() == noErr);
        CHECK(GetHandleSize(desc) == 36);

        if (*desc && GetHandleSize(desc) == 36) {
            SoundDescription *d = (SoundDescription *)*desc;

            CHECK(d->dataFormat == format);
            CHECK(d->numChannels == channels);
            CHECK(d->sampleRate == (rate << 16));
            CHECK(d->sampleSize == 16);
        }

        read_samples(media,pcm,0,100,channels,seed,0,0);
        read_samples(media,pcm,10,70,channels,seed,0,70);
        read_samples(media,pcm,24,10,channels,seed,0,10);
        read_samples(media,pcm,90,10,channels,seed,0,40);

        read_samples(media,pcm,11,5,channels,seed,
                     5*channels*2+1,20);

        TimeValue time = -1, duration = -1;
        long number = -1;

        SampleNumToMediaTime(media,25,&time,&duration);
        CHECK(GetMoviesError() == noErr);
        CHECK(time == 24 && duration == 1);

        MediaTimeToSampleNum(media,24,&number,&time,&duration);
        CHECK(GetMoviesError() == noErr);
        CHECK(number == 25 && time == 24 && duration == 1);
    }

    if (pcm)
        DisposeHandle(pcm);
    if (desc)
        DisposeHandle(desc);

    DisposeMovie(m);

    if (failures == before)
        ++good;
}

