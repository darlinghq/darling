static OSErr import_memory(const unsigned char *bytes,
                           size_t length, Movie *movie)
{
    unsigned char *copy=malloc(length);
    if (!copy)
        return memFullErr;

    memcpy(copy,bytes,length);
    PointerDataRefRecord rec={copy,(Size)length};
    PointerDataRefPtr rp=&rec;

    OSErr error=NewMovieFromDataRef(
        movie,0,NULL,(Handle)&rp,PointerDataHandlerSubType);

    memset(copy,0xa5,length);
    free(copy);

    return error;
}

static OSErr import_file(const unsigned char *bytes,
                         size_t length, Movie *movie)
{
    char path[]="/tmp/qt-up09-XXXXXX";
    FSRef ref;
    short fork=-1;
    int fd=mkstemp(path);
    if (fd<0)
        return ioErr;

    ssize_t count=write(fd,bytes,length);
    close(fd);

    if (count!=(ssize_t)length) {
        unlink(path);
        return ioErr;
    }

    OSErr error=FSPathMakeRef((const UInt8*)path,&ref,NULL);
    if (error==noErr)
        error=FSOpenFork(&ref,0,NULL,fsRdPerm,&fork);

    if (error==noErr) {
        error=NewMovieFromFile(movie,fork,NULL,NULL,0,NULL);
        FSCloseFork(fork);
    }

    unlink(path);
    return error;
}

static void verify_bytes(Handle h, unsigned start,
                          unsigned bytes, unsigned seed)
{
    CHECK(GetHandleSize(h)==(long)bytes);
    if (!*h || GetHandleSize(h)<(long)bytes)
        return;

    for (unsigned i=0;i<bytes;++i) {
        unsigned j=start+i;
        CHECK((unsigned char)(*h)[i]==
              ((j*29+seed+(j>>4))&255));
    }
}

static void verify_description(Handle h, OSType fmt,
                                unsigned channels, unsigned rate)
{
    CHECK(GetHandleSize(h)==36);
    if (!*h || GetHandleSize(h)!=36)
        return;

    const SoundDescription *d=(const SoundDescription*)*h;

    CHECK(d->descSize==36);
    CHECK(d->dataFormat==fmt);
    CHECK(d->dataRefIndex==1);
    CHECK(d->version==0);
    CHECK(d->numChannels==channels);
    CHECK(d->sampleSize==16);
    CHECK(d->sampleRate==(rate<<16));
}

static void exercise(const unsigned char *buf, size_t len,
                     OSType fmt, unsigned channels,
                     unsigned rate, unsigned seed, int file)
{
    Movie m=NULL;
    OSErr error=file ? import_file(buf,len,&m) :
                       import_memory(buf,len,&m);

    CHECK(error==noErr);
    CHECK(m!=NULL);
    if (!m) return;

    CHECK(GetMovieTrackCount(m)==1);
    Track t=GetMovieIndTrack(m,1);
    CHECK(t!=NULL);

    if (!t) {
        DisposeMovie(m);
        return;
    }

    Media media=GetTrackMedia(t);
    CHECK(media!=NULL);
    CHECK(GetMediaSampleCount(media)==100);
    CHECK(GetMediaTimeScale(media)==(TimeScale)rate);
    CHECK(GetMediaSampleDescriptionCount(media)==1);

    Handle h=NewHandle(1);
    Handle desc=NewHandle(1);

    if (!h || !desc) {
        ++failures;
        if (h) DisposeHandle(h);
        if (desc) DisposeHandle(desc);
        DisposeMovie(m);
        return;
    }

    GetMediaSampleDescription(
        media,1,(SampleDescriptionHandle)desc);
    CHECK(GetMoviesError()==noErr);
    verify_description(desc,fmt,channels,rate);

    SInt32 bytes=-1, samples=-1, index=-1;
    TimeValue time=-1, duration=-1;
    SInt16 flags=-1;
    unsigned frameBytes=channels*2;

    error=GetMediaSample(
        media,h,0,&bytes,10,&time,&duration,
        (SampleDescriptionHandle)desc,&index,4,&samples,&flags);

    CHECK(error==noErr);
    CHECK(bytes==(SInt32)(4*frameBytes));
    CHECK(samples==4);
    CHECK(time==10);
    CHECK(duration==1);
    CHECK(index==1);
    CHECK(flags==0);
    verify_bytes(h,10*frameBytes,4*frameBytes,seed);
    verify_description(desc,fmt,channels,rate);

    CHECK(GetMediaSample(
        media,h,2*frameBytes+1,&bytes,25,NULL,NULL,NULL,
        NULL,10,&samples,NULL)==noErr);

    CHECK(samples==2);
    verify_bytes(h,25*frameBytes,2*frameBytes,seed);

    CHECK(GetMediaSample(
        media,h,0,&bytes,0,NULL,NULL,NULL,
        NULL,0,&samples,NULL)==noErr);

    CHECK(samples==100);
    verify_bytes(h,0,100*frameBytes,seed);

    CHECK(GetMediaSample(
        media,h,1,NULL,0,NULL,NULL,NULL,NULL,1,NULL,NULL)
        ==maxSizeToGrowTooSmall);

    CHECK(GetMediaSample(
        media,h,0,NULL,-1,NULL,NULL,NULL,NULL,1,NULL,NULL)
        ==timeNotInMedia);

    CHECK(GetMediaSample(
        media,NULL,0,NULL,0,NULL,NULL,NULL,NULL,1,NULL,NULL)
        ==paramErr);

    verify_bytes(h,0,100*frameBytes,seed);

    GetMediaSampleDescription(
        media,2,(SampleDescriptionHandle)desc);
    CHECK(GetMoviesError()!=noErr);
    verify_description(desc,fmt,channels,rate);

    DisposeMovie(m);

    CHECK(GetMediaSample(
        media,h,0,NULL,0,NULL,NULL,NULL,NULL,1,NULL,NULL)
        ==invalidMedia);

    DisposeHandle(h);
    DisposeHandle(desc);
}
