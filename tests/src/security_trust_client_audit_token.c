static int failures;
#define CHECK(cond, what) do { if (!(cond)) { printf("FAIL: %s\n", what); failures++; } else printf("PASS: %s\n", what); } while (0)

static SecTrustRef makeTrust(SecCertificateRef certificate, bool anchored)
{
    SecPolicyRef policy = SecPolicyCreateBasicX509();
    SecTrustRef trust = NULL;
    OSStatus status = SecTrustCreateWithCertificates(certificate, policy, &trust);
    CFRelease(policy);
    if (status != errSecSuccess)
        return NULL;
    if (anchored) {
        CFArrayRef anchors = CFArrayCreate(NULL, (const void **)&certificate, 1, &kCFTypeArrayCallBacks);
        SecTrustSetAnchorCertificates(trust, anchors);
        CFRelease(anchors);
    }
    return trust;
}

int main(void)
{
    CFDataRef der = CFDataCreate(NULL, certificateDER, sizeof(certificateDER));
    SecCertificateRef certificate = SecCertificateCreateWithData(NULL, der);
    CFRelease(der);
    CHECK(certificate != NULL, "the test certificate parses");
    if (!certificate)
        return 1;

    // An audit_token_t is eight 32-bit words; the contents do not matter here.
    unsigned int words[8];
    memset(words, 0x5a, sizeof(words));
    CFDataRef token = CFDataCreate(NULL, (const UInt8 *)words, sizeof(words));

    CHECK(SecTrustSetClientAuditToken(NULL, token) == errSecParam, "a NULL trust gives errSecParam");

    for (int anchored = 0; anchored <= 1; anchored++) {
        const char *expected = anchored ? "trusted" : "untrusted";
        char what[128];

        SecTrustRef before = makeTrust(certificate, anchored);
        CHECK(before != NULL, "a trust is created");
        if (!before)
            continue;
        CHECK(SecTrustSetClientAuditToken(before, token) == errSecSuccess, "setting a token succeeds");
        bool result = SecTrustEvaluateWithError(before, NULL);
        snprintf(what, sizeof(what), "a token set before evaluation leaves the chain %s", expected);
        CHECK(result == (bool)anchored, what);

        SecTrustRef after = makeTrust(certificate, anchored);
        result = SecTrustEvaluateWithError(after, NULL);
        CHECK(SecTrustSetClientAuditToken(after, token) == errSecSuccess, "setting a token after evaluation succeeds");
        result = SecTrustEvaluateWithError(after, NULL);
        snprintf(what, sizeof(what), "a token set after evaluation leaves the chain %s", expected);
        CHECK(result == (bool)anchored, what);

        CHECK(SecTrustSetClientAuditToken(after, NULL) == errSecSuccess, "clearing the token succeeds");
        result = SecTrustEvaluateWithError(after, NULL);
        snprintf(what, sizeof(what), "clearing the token leaves the chain %s", expected);
        CHECK(result == (bool)anchored, what);

        CFRelease(before);
        CFRelease(after);
    }

    CFRelease(token);
    CFRelease(certificate);
    printf("%s\n", failures ? "FAILED" : "ALL PASSED");
    return failures != 0;
}
