// The symbol of a formatter of the original behavior is its attributed string (macOS keeps the
// symbol getters of the current behavior empty for it); other implementations only have the symbol.
static NSString *symbol(NSNumberFormatter *f, SEL attributed, SEL plain)
{
    if ([f respondsToSelector:attributed])
        return [[f performSelector:attributed] string];
    return [f performSelector:plain];
}

static BOOL same(NSString *s, const char *c)
{
    return [s isEqualToString:[NSString stringWithUTF8String:c]];
}

static void checkAttributes(const char *name, NSDictionary *d, const char *const attribute[2])
{
    if (attribute[0] == NULL)
    {
        if ([d count] != 0)
        {
            printf("FAIL %s: unexpected text attributes\n", name);
            failures++;
        }
        return;
    }
    NSString *key = [NSString stringWithUTF8String:attribute[0]];
    if ([d count] != 1 || ![d[key] isEqual:[NSString stringWithUTF8String:attribute[1]]])
    {
        printf("FAIL %s: text attributes %s\n", name, [[d description] UTF8String]);
        failures++;
    }
}

int main(void)
{
    setvbuf(stdout, NULL, _IOLBF, 0);
    @autoreleasepool
    {
        for (size_t i = 0; i < sizeof(cases) / sizeof(cases[0]); i++)
        {
            const Case *c = &cases[i];
            NSNumberFormatter *f = decodeData(hexData(c->hex));
            if (![f isKindOfClass:[NSNumberFormatter class]])
            {
                printf("FAIL %s: not an NSNumberFormatter\n", c->name);
                failures++;
                continue;
            }
            if (c->positiveFormat != NULL && ![f.positiveFormat isEqualToString:[NSString stringWithUTF8String:c->positiveFormat]])
            {
                printf("FAIL %s: positive format [%s]\n", c->name, [f.positiveFormat UTF8String]);
                failures++;
            }
            if (c->negativeFormat != NULL && ![f.negativeFormat isEqualToString:[NSString stringWithUTF8String:c->negativeFormat]])
            {
                printf("FAIL %s: negative format [%s]\n", c->name, [f.negativeFormat UTF8String]);
                failures++;
            }
            if ([f hasThousandSeparators] != c->hasThousandSeparators || [f localizesFormat] != c->localizesFormat || [f allowsFloats] != c->allowsFloats)
            {
                printf("FAIL %s: flags thousand=%d localizes=%d floats=%d\n", c->name, [f hasThousandSeparators], [f localizesFormat], [f allowsFloats]);
                failures++;
            }
            if (c->thousandSeparator != NULL && !same([f thousandSeparator], c->thousandSeparator))
            {
                printf("FAIL %s: thousand separator [%s]\n", c->name, [[f thousandSeparator] UTF8String]);
                failures++;
            }
            if (c->decimalSeparator != NULL && !same([f decimalSeparator], c->decimalSeparator))
            {
                printf("FAIL %s: decimal separator [%s]\n", c->name, [[f decimalSeparator] UTF8String]);
                failures++;
            }
            NSString *zero = symbol(f, @selector(attributedStringForZero), @selector(zeroSymbol));
            NSString *nilString = symbol(f, @selector(attributedStringForNil), @selector(nilSymbol));
            NSString *notANumber = symbol(f, @selector(attributedStringForNotANumber), @selector(notANumberSymbol));
            if (!same(zero, c->zero) || !same(nilString, c->nilString) || !same(notANumber, c->notANumber))
            {
                printf("FAIL %s: symbols zero=[%s] nil=[%s] nan=[%s]\n", c->name, [zero UTF8String], [nilString UTF8String], [notANumber UTF8String]);
                failures++;
            }
            checkAttributes(c->name, [f textAttributesForPositiveValues], c->positiveAttribute);
            checkAttributes(c->name, [f textAttributesForNegativeValues], c->negativeAttribute);
        }

        // a decoded formatter is a working formatter: it formats with what the archive says
        NSNumberFormatter *f = decodeData(hexData(fx_nf_minmax_seps));
        CHECK([[f stringFromNumber:@1234.5] isEqualToString:@"1'234,5"]);
        CHECK([[f stringFromNumber:@-1234.5] isEqualToString:@"-1'234,5"]);
    }
    printf(failures ? "FAIL\n" : "PASS\n");
    return failures != 0;
}
