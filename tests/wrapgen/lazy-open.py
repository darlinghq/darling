# A wrapper generated by wrapgen opens its host library when a wrapped function
# is first used, not when the wrapper is loaded. A program that links a wrapper
# for a library the host does not have must therefore load and run as long as it
# never calls into that library, and only a call may abort.
#
# The test builds a host library with a made-up soname, generates a wrapper for
# it, deletes the library, links a guest program against the wrapper and runs it
# inside Darling in two ways: without calling the library (must succeed) and
# calling a wrapped function (must abort, as the library is missing).
#
# Usage: lazy-open.py --wrapgen WRAPGEN --source-dir DARLING_SOURCE
#                     --scripts DARLING_GUEST_TESTING_SCRIPTS [--arch x86_64|i386]
# CC selects the host compiler for the fixture (default: cc).

import argparse
import os
import shlex
import subprocess
import sys
import tempfile

# Where the guest sees the host filesystem.
GUEST_HOST_ROOT = "/Volumes/SystemRoot"

FIXTURE = """
int lazyopen_fixture_call(int x) { return x + 1; }
"""

PROGRAM = """
#include <stdio.h>
#include <string.h>
extern int lazyopen_fixture_call(int x);
int main(int argc, char **argv) {
	if (argc > 1 && !strcmp(argv[1], "call"))
		return lazyopen_fixture_call(1);
	puts("loaded");
	return 0;
}
"""

failures = 0


def check(cond, message):
    global failures
    print(("PASS " if cond else "FAIL ") + message)
    if not cond:
        failures += 1


def run(args, **kwargs):
    return subprocess.run(args, stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                          universal_newlines=True, **kwargs)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--wrapgen", required=True)
    parser.add_argument("--source-dir", required=True)
    parser.add_argument("--scripts", required=True)
    parser.add_argument("--arch", default="x86_64")
    opts = parser.parse_args()
    cc = shlex.split(os.environ.get("CC", "cc"))
    guest_cc = os.path.join(opts.scripts, "guest-cc.sh")
    elfcalls = os.path.join(opts.source_dir, "src", "startup", "mldr", "elfcalls")

    with tempfile.TemporaryDirectory(prefix="wrapgen-lazy-", dir=os.environ.get("TMPDIR")) as tmp:
        def path(name):
            return os.path.join(tmp, name)

        with open(path("fixture.c"), "w") as f:
            f.write(FIXTURE)
        with open(path("program.c"), "w") as f:
            f.write(PROGRAM)

        r = run(cc + ["-shared", "-fPIC", "-Wl,-soname,libdarling-lazyopen-fixture.so.7",
                      path("fixture.c"), "-o", path("fixture.so")])
        if r.returncode != 0:
            print(r.stdout)
            return 1
        r = run([opts.wrapgen, path("fixture.so"), path("wrapper.c"), path("vars.h")])
        if r.returncode != 0:
            print(r.stdout)
            return 1
        os.unlink(path("fixture.so"))

        wrapper = path("libdarling-lazyopen.dylib")
        r = run([guest_cc, "-a", opts.arch, "-o", wrapper, path("wrapper.c"),
                 "-dynamiclib", "-install_name", GUEST_HOST_ROOT + wrapper, "-I", elfcalls])
        check(r.returncode == 0, "wrapper builds as a guest dylib")
        if r.returncode != 0:
            print(r.stdout)
            return 1
        program = path("program")
        r = run([guest_cc, "-a", opts.arch, "-o", program, path("program.c"), wrapper])
        check(r.returncode == 0, "program links against the wrapper")
        if r.returncode != 0:
            print(r.stdout)
            return 1

        for args, label, want_ok in (([], "program that never calls the library runs", True),
                                     (["call"], "calling a wrapped function aborts when the library is missing", False)):
            out = path("out.txt")
            with open(out, "w") as o:
                r = subprocess.run(["timeout", "-s", "KILL", "60", "darling", "shell", GUEST_HOST_ROOT + program] + args,
                                   stdin=subprocess.DEVNULL, stdout=o, stderr=subprocess.STDOUT)
            text = open(out).read()
            if want_ok:
                check(r.returncode == 0 and "loaded" in text, label)
            else:
                check(r.returncode != 0 and "loaded" not in text and "libdarling-lazyopen-fixture" in text, label)
            if (r.returncode == 0) != want_ok:
                print(text)

    print("%d failure(s)" % failures)
    return 1 if failures else 0


sys.exit(main())
